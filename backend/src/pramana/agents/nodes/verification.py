"""Verification Agent: turns candidates into evidence and checks it before anything is written.

* fuses the three rankings, re-checks policy on every passage, reranks, expands context
* decides whether the evidence is good enough to answer from at all
* flags superseded versions and passages carrying injected instructions
* applies reader masking and the LLM egress policy
"""

from __future__ import annotations

from dataclasses import replace
from typing import Any

from pramana.agents.state import AgentDeps, PipelineState
from pramana.privacy.pii import mask_for_reader
from pramana.privacy.risk import injection_flags
from pramana.retrieval.retriever import Evidence

RELEVANCE_WINDOW = 9.0
RELEVANCE_FLOOR = -6.0


async def run(state: PipelineState, deps: AgentDeps) -> dict[str, Any]:
    access = state["access"]
    scope, egress = access.scope, access.egress
    result = await deps.retriever.build_evidence(
        state["retrieval_query"],
        principal=state["principal"],
        vectors=state["vector_candidates"],
        graph=state["graph_candidates"],
    )
    notes: list[str] = []
    updates: dict[str, Any] = {"retrieval": result}

    # 1. Relevance: keep passages close to the best one; decide whether to answer at all.
    top = result.evidence[0].rerank_score if result.evidence else float("-inf")
    kept = [e for e in result.evidence if e.rerank_score >= max(top - RELEVANCE_WINDOW, RELEVANCE_FLOOR)]
    sufficient = bool(kept) and top >= deps.settings.min_evidence_score

    # 2. Passages that carry instructions aimed at the model are not given to it.
    suspicious = [e for e in kept if injection_flags(e.text)]
    if suspicious:
        kept = [e for e in kept if e not in suspicious]
        notes.append(f"{len(suspicious)} passage(s) excluded: they contain instructions aimed at an AI model")

    stale = [e for e in kept if not e.is_current]
    if stale:
        notes.append(f"{len(stale)} passage(s) come from a superseded version and are marked as such")

    # References are renumbered after filtering so that the answer cites E1…En without gaps.
    kept = [replace(e, ref=f"E{i}") for i, e in enumerate(kept, start=1)]

    # 3. What the reader may see: personal data masked unless the reader holds pii:read.
    reader_evidence = [
        replace(e, text=mask_for_reader(e.text, sensitivity_rank=e.sensitivity_rank, can_read_pii=scope.can_read_pii))
        for e in kept
    ]

    # 4. LLM egress: what may leave this machine in a prompt.
    blocked = [e.ref for e in reader_evidence if e.sensitivity_rank > egress.max_rank]
    if not blocked:
        route = "external"
    elif deps.llm.has_local_provider():
        route = "local"
        notes.append("Evidence above the egress ceiling: the answer is generated by the local model only")
    else:
        route = "extractive"
        notes.append(
            "Evidence above the egress ceiling and no local model configured: "
            "the answer is quoted directly from the sources instead of being generated"
        )
    if not deps.llm.configured:
        route = "extractive"
        notes.append("No LLM provider configured: the answer is quoted directly from the sources")

    if route == "external":
        pseudonymizer = state["pseudonymizer"]
        llm_evidence = [
            replace(
                e,
                text=pseudonymizer.protect(
                    e.text, sensitivity_rank=e.sensitivity_rank, pseudonymize_contact=egress.pseudonymize_names
                ),
            )
            for e in reader_evidence
        ]
        if pseudonymizer.placeholder_count:
            notes.append(
                f"{pseudonymizer.placeholder_count} personal value(s) replaced by placeholders before the LLM call"
            )
    else:
        llm_evidence = reader_evidence

    updates.update({"evidence": reader_evidence, "llm_evidence": llm_evidence, "route": route, "evidence_notes": notes})
    if not sufficient:
        updates["outcome"] = "abstained"
        updates["outcome_reason"] = "no_evidence" if not result.evidence else "insufficient_evidence"

    documents = {e.document_id for e in reader_evidence}
    updates["_summary"] = (
        f"{len(reader_evidence)} passages from {len(documents)} document(s) kept of "
        f"{result.candidates_considered} candidates; best relevance {top:+.1f}; "
        + ("sufficient to answer" if sufficient else "not sufficient to answer")
        + f"; route: {route}"
    )
    updates["_details"] = {
        "candidates": result.candidates_considered,
        "kept": len(reader_evidence),
        "top_relevance": None if top == float("-inf") else round(top, 3),
        "sufficient": sufficient,
        "route": route,
        "blocked_from_egress": blocked,
        "superseded": [e.ref for e in stale],
        "excluded_for_injection": len(suspicious),
        "notes": notes,
        "timings_ms": result.timings_ms,
        "evidence": [_brief(e) for e in reader_evidence],
    }
    return updates


def _brief(evidence: Evidence) -> dict[str, Any]:
    return {
        "ref": evidence.ref,
        "title": evidence.title,
        "section": evidence.section_path,
        "sensitivity_rank": evidence.sensitivity_rank,
        "department": evidence.department,
        "relevance": round(evidence.rerank_score, 3),
        "found_by": evidence.found_by,
        "current": evidence.is_current,
    }
