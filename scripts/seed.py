"""Seed departments, roles and the demo personas, then publish the first policy version.

    python scripts/seed.py

Safe to re-run. The persona password is DEMO_PASSWORD from .env (generated by init_env.py).
"""

from __future__ import annotations

import asyncio
import sys

from pramana.auth.seed import PERSONAS, seed_personas, seed_reference_data
from pramana.privacy.policy import PolicyEngine, PolicyStore
from pramana.shared.config import get_settings
from pramana.shared.db import dispose_engine, session_scope


async def main() -> int:
    settings = get_settings()
    settings.require_secrets()
    if settings.demo_password is None or not settings.demo_password.get_secret_value():
        print("DEMO_PASSWORD is not set. Run scripts/init_env.py first.")
        return 1

    engine = PolicyEngine(settings.opa_url)
    try:
        async with session_scope() as db:
            await seed_reference_data(db)
            created = await seed_personas(db, settings.demo_password.get_secret_value())
            store = PolicyStore(db, engine)
            version = await store.active()
            if version is None:
                version = await store.publish(note="Initial policy", created_by=None)
            else:
                await engine.load(rego=version.rego, data=version.data, version=version.version)
    finally:
        await engine.close()
        await dispose_engine()

    print(f"roles and departments: ok; active policy version {version.version}")
    print(f"personas created: {len(created)} (of {len(PERSONAS)}); password is DEMO_PASSWORD in .env")
    for persona in PERSONAS:
        print(f"  {persona.role:<19} {persona.department:<12} {persona.region:<7} {persona.email}")
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
